package com.repopilot.approval.entity;

import com.repopilot.change.entity.CodeChange;
import com.repopilot.project.entity.Project;
import com.repopilot.repository.entity.Repository;
import com.repopilot.task.entity.Task;
import com.repopilot.user.entity.User;
import jakarta.persistence.*;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "publication_audit_events")
public class PublicationAuditEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "event_sequence", insertable = false, updatable = false, columnDefinition = "BIGINT GENERATED BY DEFAULT AS IDENTITY")
    private Long eventSequence;

    @Column(name = "event_timestamp", nullable = false, updatable = false)
    private Instant eventTimestamp = Instant.now();

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "project_id", updatable = false)
    private Project project;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "repository_id", updatable = false)
    private Repository repository;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "task_id", updatable = false)
    private Task task;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "code_change_id", updatable = false)
    private CodeChange codeChange;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "approval_id", updatable = false)
    private HumanApproval approval;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "publication_id", updatable = false)
    private PullRequestPublication publication;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "actor_user_id", updatable = false)
    private User actorUser;

    @Column(name = "actor_email", updatable = false)
    private String actorEmail;

    @Column(name = "actor_role", updatable = false)
    private String actorRole;

    @Enumerated(EnumType.STRING)
    @Column(name = "event_type", nullable = false, updatable = false)
    private AuditEventType eventType;

    @Column(name = "previous_state", updatable = false)
    private String previousState;

    @Column(name = "resulting_state", updatable = false)
    private String resultingState;

    @Column(name = "github_repo_id", updatable = false)
    private String githubRepoId;

    @Column(name = "repo_owner", updatable = false)
    private String repoOwner;

    @Column(name = "repo_name", updatable = false)
    private String repoName;

    @Column(name = "base_branch", updatable = false)
    private String baseBranch;

    @Column(name = "branch_name", updatable = false)
    private String branchName;

    @Column(name = "base_sha", updatable = false)
    private String baseSha;

    @Column(name = "commit_sha", updatable = false)
    private String commitSha;

    @Column(name = "parent_commit_sha", updatable = false)
    private String parentCommitSha;

    @Column(name = "tree_sha", updatable = false)
    private String treeSha;

    @Column(name = "diff_hash", updatable = false)
    private String diffHash;

    @Column(name = "github_pr_number", updatable = false)
    private Long githubPrNumber;

    @Column(name = "pr_url", updatable = false)
    private String prUrl;

    @Column(name = "outcome_category", updatable = false)
    private String outcomeCategory;

    @Column(name = "reason_code", updatable = false)
    private String reasonCode;

    @Column(name = "summary", updatable = false)
    private String summary;

    @Column(name = "metadata_json", updatable = false)
    private String metadataJson;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    public PublicationAuditEvent() {
    }

    // Getters
    public UUID getId() { return id; }
    public Long getEventSequence() { return eventSequence; }
    public Instant getEventTimestamp() { return eventTimestamp; }
    public Project getProject() { return project; }
    public Repository getRepository() { return repository; }
    public Task getTask() { return task; }
    public CodeChange getCodeChange() { return codeChange; }
    public HumanApproval getApproval() { return approval; }
    public PullRequestPublication getPublication() { return publication; }
    public User getActorUser() { return actorUser; }
    public String getActorEmail() { return actorEmail; }
    public String getActorRole() { return actorRole; }
    public AuditEventType getEventType() { return eventType; }
    public String getPreviousState() { return previousState; }
    public String getResultingState() { return resultingState; }
    public String getGithubRepoId() { return githubRepoId; }
    public String getRepoOwner() { return repoOwner; }
    public String getRepoName() { return repoName; }
    public String getBaseBranch() { return baseBranch; }
    public String getBranchName() { return branchName; }
    public String getBaseSha() { return baseSha; }
    public String getCommitSha() { return commitSha; }
    public String getParentCommitSha() { return parentCommitSha; }
    public String getTreeSha() { return treeSha; }
    public String getDiffHash() { return diffHash; }
    public Long getGithubPrNumber() { return githubPrNumber; }
    public String getPrUrl() { return prUrl; }
    public String getOutcomeCategory() { return outcomeCategory; }
    public String getReasonCode() { return reasonCode; }
    public String getSummary() { return summary; }
    public String getMetadataJson() { return metadataJson; }
    public Instant getCreatedAt() { return createdAt; }

    // Setters for initialization before persist
    public void setId(UUID id) { this.id = id; }
    public void setEventTimestamp(Instant eventTimestamp) { this.eventTimestamp = eventTimestamp; }
    public void setProject(Project project) { this.project = project; }
    public void setRepository(Repository repository) { this.repository = repository; }
    public void setTask(Task task) { this.task = task; }
    public void setCodeChange(CodeChange codeChange) { this.codeChange = codeChange; }
    public void setApproval(HumanApproval approval) { this.approval = approval; }
    public void setPublication(PullRequestPublication publication) { this.publication = publication; }
    public void setActorUser(User actorUser) { this.actorUser = actorUser; }
    public void setActorEmail(String actorEmail) { this.actorEmail = actorEmail; }
    public void setActorRole(String actorRole) { this.actorRole = actorRole; }
    public void setEventType(AuditEventType eventType) { this.eventType = eventType; }
    public void setPreviousState(String previousState) { this.previousState = previousState; }
    public void setResultingState(String resultingState) { this.resultingState = resultingState; }
    public void setGithubRepoId(String githubRepoId) { this.githubRepoId = githubRepoId; }
    public void setRepoOwner(String repoOwner) { this.repoOwner = repoOwner; }
    public void setRepoName(String repoName) { this.repoName = repoName; }
    public void setBaseBranch(String baseBranch) { this.baseBranch = baseBranch; }
    public void setBranchName(String branchName) { this.branchName = branchName; }
    public void setBaseSha(String baseSha) { this.baseSha = baseSha; }
    public void setCommitSha(String commitSha) { this.commitSha = commitSha; }
    public void setParentCommitSha(String parentCommitSha) { this.parentCommitSha = parentCommitSha; }
    public void setTreeSha(String treeSha) { this.treeSha = treeSha; }
    public void setDiffHash(String diffHash) { this.diffHash = diffHash; }
    public void setGithubPrNumber(Long githubPrNumber) { this.githubPrNumber = githubPrNumber; }
    public void setPrUrl(String prUrl) { this.prUrl = prUrl; }
    public void setOutcomeCategory(String outcomeCategory) { this.outcomeCategory = outcomeCategory; }
    public void setReasonCode(String reasonCode) { this.reasonCode = reasonCode; }
    public void setSummary(String summary) { this.summary = summary; }
    public void setMetadataJson(String metadataJson) { this.metadataJson = metadataJson; }
}
